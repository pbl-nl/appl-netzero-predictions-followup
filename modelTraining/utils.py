from modelTraining.config.base import ModelTrainingConfig


@dataclass
class SplitArtifacts:
    """Loaded modelPreparation artifacts for one split."""

    split: str
    df: pd.DataFrame
    feature_columns: list[str]
    partitions: dict[str, list[list[Any]]]


def load_split_artifacts(config: ModelTrainingConfig, split: str) -> SplitArtifacts:
    """Load split-level dataset and metadata generated by modelPreparation."""
    split_dir = config.model_ready_dir / split
    pre_split_path = split_dir / "pre_split_data.csv"
    split_indices_path = split_dir / "split_indices.json"
    feature_list_path = split_dir / "feature_list.json"

    missing = [
        str(path)
        for path in [pre_split_path, split_indices_path, feature_list_path]
        if not path.exists()
    ]
    if missing:
        raise FileNotFoundError(f"Missing modelPreparation artifacts for split '{split}': {missing}")

    df = pd.read_csv(pre_split_path)

    with split_indices_path.open("r", encoding="utf-8") as f:
        split_indices_payload = json.load(f)
    with feature_list_path.open("r", encoding="utf-8") as f:
        feature_list_payload = json.load(f)

    feature_columns = feature_list_payload["feature_columns"]
    partitions = split_indices_payload["partitions"]

    return SplitArtifacts(split=split, df=df, feature_columns=feature_columns, partitions=partitions)


def to_key_tuples(rows: Iterable[Iterable[Any]]) -> set[tuple[str, int]]:
    """Convert [[country, year], ...] lists to typed key tuples."""
    return {(str(country), int(year)) for country, year in rows}


def apply_partition_masks(df: pd.DataFrame, partitions: dict[str, list[list[Any]]]) -> dict[str, pd.Series]:
    """Build boolean masks for train/valid/forecast partitions."""
    keys = list(zip(df["country"].astype(str), df["year"].astype(int)))
    key_to_idx = {key: i for i, key in enumerate(keys)}

    masks: dict[str, pd.Series] = {}
    for part_name in ["train", "valid", "forecast"]:
        idxs = [
            key_to_idx[(str(country), int(year))]
            for country, year in partitions.get(part_name, [])
            if (str(country), int(year)) in key_to_idx
        ]
        mask = pd.Series(False, index=df.index)
        if idxs:
            mask.iloc[idxs] = True
        masks[part_name] = mask
    return masks


def split_X_y(
    df: pd.DataFrame,
    feature_columns: list[str],
    scenario: str,
    mask: pd.Series,
) -> tuple[pd.DataFrame, pd.Series]:
    """Return X/y subset for a partition mask."""
    subset = df.loc[mask].copy()
    X = subset[["country", "year", *feature_columns]].reset_index(drop=True)
    y = subset[scenario].reset_index(drop=True)
    return X, y


def drop_missing_target(
    X: pd.DataFrame,
    y: pd.Series,
) -> tuple[pd.DataFrame, pd.Series]:
    """Drop rows where target is missing or non-finite."""
    y_num = pd.to_numeric(y, errors="coerce")
    keep = y_num.notna() & np.isfinite(y_num.to_numpy(dtype=float))
    return X.loc[keep].reset_index(drop=True), y_num.loc[keep].reset_index(drop=True)


def safe_log_target_with_shift(
    y: pd.Series,
    shift_constant: float,
) -> tuple[np.ndarray, int]:
    """Apply log(y + c) with a minimum clip for out-of-range validation values.

    Returns (log_values, n_clipped) where n_clipped is the number of values
    that required clipping to 1e-12 before taking the log.
    """
    y_num = pd.to_numeric(y, errors="coerce").to_numpy(dtype=float)
    if not np.isfinite(y_num).all():
        raise ValueError("Target contains non-finite values")
    raw_shifted = y_num + float(shift_constant)
    n_clipped = int(np.sum(raw_shifted <= 0))
    shifted = np.clip(raw_shifted, a_min=1e-12, a_max=None)
    return np.log(shifted), n_clipped


def bootstrap_rows_country_stratified(
    X: pd.DataFrame,
    y: pd.Series,
    seed: int,
) -> tuple[pd.DataFrame, pd.Series]:
    """Row bootstrap with at least one sampled row per training country."""
    if len(X) != len(y):
        raise ValueError("X and y lengths mismatch in bootstrap")
    if len(X) == 0:
        raise ValueError("Cannot bootstrap empty training set")

    rng = np.random.default_rng(seed)
    n = len(X)

    countries = X["country"].astype(str)
    indices_by_country: dict[str, list[int]] = {}
    for idx, country in enumerate(countries.tolist()):
        indices_by_country.setdefault(country, []).append(idx)

    guaranteed = [
        int(rng.choice(country_idxs))
        for country_idxs in indices_by_country.values()
    ]

    if len(guaranteed) > n:
        chosen = rng.choice(np.array(guaranteed, dtype=int), size=n, replace=False)
        sampled_idx = chosen.astype(int).tolist()
    else:
        remaining = n - len(guaranteed)
        if remaining > 0:
            sampled_rest = rng.choice(np.arange(n), size=remaining, replace=True).astype(int).tolist()
        else:
            sampled_rest = []
        sampled_idx = guaranteed + sampled_rest
        rng.shuffle(sampled_idx)

    X_boot = X.iloc[sampled_idx].reset_index(drop=True)
    y_boot = y.iloc[sampled_idx].reset_index(drop=True)
    return X_boot, y_boot


def bootstrap_rows(
    X: pd.DataFrame,
    y: pd.Series,
    seed: int,
) -> tuple[pd.DataFrame, pd.Series]:
    """Simple fixed-size row bootstrap with replacement."""
    if len(X) != len(y):
        raise ValueError("X and y lengths mismatch in bootstrap")
    if len(X) == 0:
        raise ValueError("Cannot bootstrap empty training set")

    rng = np.random.default_rng(seed)
    sampled_idx = rng.choice(np.arange(len(X)), size=len(X), replace=True)
    X_boot = X.iloc[sampled_idx].reset_index(drop=True)
    y_boot = y.iloc[sampled_idx].reset_index(drop=True)
    return X_boot, y_boot


def bootstrap_country_sequences(
    X: pd.DataFrame,
    y: pd.Series,
    seed: int,
) -> tuple[pd.DataFrame, pd.Series]:
    """Bootstrap countries and keep full sequences per selected country."""
    if len(X) != len(y):
        raise ValueError("X and y lengths mismatch in bootstrap")
    if len(X) == 0:
        raise ValueError("Cannot bootstrap empty training set")

    rng = np.random.default_rng(seed)
    grouped = X.assign(__y=y.values).groupby("country", sort=False)
    countries = list(grouped.groups.keys())
    sampled_countries = rng.choice(np.array(countries, dtype=object), size=len(countries), replace=True)

    pieces: list[pd.DataFrame] = []
    for draw_id, country in enumerate(sampled_countries):
        chunk = grouped.get_group(country).copy()
        chunk["__bootstrap_draw"] = draw_id
        pieces.append(chunk)

    boot = pd.concat(pieces, ignore_index=True)
    boot = boot.sort_values(["__bootstrap_draw", "country", "year"]).reset_index(drop=True)

    y_boot = boot.pop("__y").reset_index(drop=True)
    boot = boot.drop(columns=["__bootstrap_draw"])
    return boot.reset_index(drop=True), y_boot


def iter_grid(grid: dict[str, list[Any]]) -> list[dict[str, Any]]:
    """Expand a cartesian grid dict to concrete parameter dictionaries."""
    if not grid:
        return [{}]
    keys = list(grid.keys())
    values = [grid[key] for key in keys]
    combos = []
    for product in itertools.product(*values):
        combos.append({k: v for k, v in zip(keys, product)})
    return combos


def compute_regression_metrics(
    y_true_log: np.ndarray,
    y_pred_log: np.ndarray,
    countries: pd.Series | None = None,
) -> dict[str, float]:
    """Compute standard + within-country metrics in log space."""
    y_true_arr = np.asarray(y_true_log, dtype=float)
    y_pred_arr = np.asarray(y_pred_log, dtype=float)

    rmse = float(np.sqrt(mean_squared_error(y_true_arr, y_pred_arr)))
    mae = float(mean_absolute_error(y_true_arr, y_pred_arr))

    try:
        r2 = float(r2_score(y_true_arr, y_pred_arr))
    except ValueError:
        r2 = float("nan")

    within_rmse = float("nan")
    if countries is not None and len(countries) == len(y_true_arr):
        country_series = countries.astype(str).reset_index(drop=True)
        frame = pd.DataFrame({
            "country": country_series,
            "y_true": y_true_arr,
            "y_pred": y_pred_arr,
        })

        group_values = []
        for _, grp in frame.groupby("country", sort=False):
            if len(grp) <= 1:
                continue
            centered_true = grp["y_true"] - grp["y_true"].mean()
            centered_pred = grp["y_pred"] - grp["y_pred"].mean()
            group_values.append(mean_squared_error(centered_true, centered_pred))

        if group_values:
            within_rmse = float(np.sqrt(np.mean(group_values)))

    return {
        "RMSE_log": rmse,
        "MAE_log": mae,
        "R2": r2,
        "Within_RMSE": within_rmse,
    }


def confidence_interval(values: np.ndarray, confidence_level: float) -> tuple[float, float]:
    """Compute central confidence interval via quantiles."""
    arr = np.asarray(values, dtype=float)
    arr = arr[np.isfinite(arr)]
    if arr.size == 0:
        return float("nan"), float("nan")

    alpha = 1.0 - confidence_level
    low = float(np.quantile(arr, alpha / 2.0))
    high = float(np.quantile(arr, 1.0 - alpha / 2.0))
    return low, high
